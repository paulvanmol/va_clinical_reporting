"""Recompute practice/SOLUTIONS.md (module 1) and practice/module2/SOLUTIONS.md (module 2). Needs pandas + tabulate."""
import pandas as pd
md=lambda t:t.to_markdown()
# ---------- Module 1
df=pd.read_csv("data/table_AE_DM.csv",dtype=str); df["AGE"]=df.AGE.astype(int)
lo=(df.AGE//5)*5; df["AGEGR5"]=lo.astype(str)+"-"+(lo+4).astype(str)
ae=df[df.AESEV.notna()]; sev=ae[ae.AESEV=="SEVERE"]; s1=df.drop_duplicates("USUBJID")
o=["# Module 1 – Solutions (expected results)\n","Generated by `scripts/expected_results.py`.\n",
f"Rows: **{len(df)}** | Subjects: **{df.USUBJID.nunique()}** | Subjects with ≥1 AE: **{ae.USUBJID.nunique()}** | AE records: **{len(ae)}**\n",
"## Exercise 2 – Planned vs actual arm (distinct subjects)\n",md(pd.DataFrame({"Planned (ARM)":df.groupby("ARM").USUBJID.nunique(),"Actual (ACTARM)":df.groupby("ACTARM").USUBJID.nunique()})),
"\nActual ≠ planned: "+", ".join(sorted(df[df.ARM!=df.ACTARM].USUBJID.unique()))+"\n",
"## Exercise 3 – Arm by Gender\n",md(pd.crosstab(s1.ACTARM,s1.SEX)),
"\n## Exercise 4 – AE Severity by Subject\n",md(pd.crosstab(ae.AESEV,ae.SEX,values=ae.USUBJID,aggfunc="nunique")),
"\nPer severity: "+", ".join(f"{k}={v}" for k,v in ae.groupby("AESEV").USUBJID.nunique().items()),
"\n> The bars add up to more than 218 because one subject can have AEs of several severities.\n",
"## Exercise 5 – Severe AEs: distinct subjects by SOC and arm\n",
md(pd.crosstab(sev.AEBODSYS,sev.ACTARM,values=sev.USUBJID,aggfunc="nunique").fillna(0).astype(int)),
f"\nSevere AE records: **{len(sev)}**, distinct subjects: **{sev.USUBJID.nunique()}**\n",
"## Exercise 6 – 5-year age group\n### Distinct subjects\n",
md(pd.crosstab(ae.AGEGR5,ae.AESEV,values=ae.USUBJID,aggfunc="nunique").fillna(0).astype(int).sort_index(ascending=False)),
"\n### AE count (frequency)\n",md(pd.crosstab(ae.AGEGR5,ae.AESEV).sort_index(ascending=False)),"\n## Exercise 7 – Subject profiles\n"]
for s in ["01-708-1019","01-701-1211"]:
    o+=[f"### {s}\n",md(df[df.USUBJID==s][["ACTARM","AGE","SEX","AESTDTC","AEDECOD","AEBODSYS","AESEV","AESER","AEREL"]].set_index("AESTDTC")),"\n"]
open("practice/SOLUTIONS.md","w").write("\n".join(o))
# ---------- Module 2
lb=pd.read_csv("data/module2/adlb.csv"); vs=pd.read_csv("data/module2/advs.csv"); ex=pd.read_csv("data/module2/adex.csv")
order=["BASELINE","WEEK 2","WEEK 8","WEEK 16","WEEK 24"]
o=["# Module 2 – Solutions (expected results)\n","Generated by `scripts/expected_results.py`.\n",
f"adex: **{len(ex)}** rows | adlb: **{len(lb)}** rows | advs: **{len(vs)}** rows\n",
"## Exercise 2 – Exposure (treatment duration in days)\n",
md(ex.groupby("ACTARM").TRTDURD.agg(Subjects="count",Minimum="min",Average="mean",Maximum="max").round(1)),
"\n### Completion and discontinuation reasons\n",md(pd.crosstab(ex.DCREAS.fillna("(completed)"),ex.ACTARM,margins=True)),
"\n## Exercise 3 – Heart rate: mean by visit and arm (beats/min)\n",
md(vs[vs.PARAMCD=="PULSE"].pivot_table(index="ACTARM",columns="AVISIT",values="AVAL",aggfunc="mean")[order].round(1)),
"\n### Subjects with post-baseline heart rate < 50 bpm\n"]
b=vs[(vs.PARAMCD=="PULSE")&(vs.AVISITN>0)&(vs.AVAL<50)]
o+=[md(b.groupby(["USUBJID","ACTARM"]).AVAL.min().rename("Lowest HR").reset_index().set_index("USUBJID")),
"\n## Exercise 4 – HbA1c: mean change from baseline (%)\n",
md(lb[(lb.PARAMCD=="HBA1C")&(lb.AVISITN>0)].pivot_table(index="ACTARM",columns="AVISIT",values="CHG",aggfunc="mean")[order[1:]].round(2)),
"\n## Exercise 5 – ALT shift table: baseline vs worst post-baseline (distinct subjects)\n"]
alt=lb[lb.PARAMCD=="ALT"]; rank={"LOW":0,"NORMAL":1,"HIGH":2}
w=alt[alt.AVISITN>0].assign(r=lambda d:d.ANRIND.map(rank)).sort_values("r").groupby("USUBJID").tail(1)
o+=[md(pd.crosstab([w.ACTARM,w.BNRIND],w.ANRIND)),
"\n## Exercise 6 – eDISH (peak post-baseline ALT ×ULN vs peak BILI ×ULN)\n"]
pk=lb[(lb.AVISITN>0)&lb.PARAMCD.isin(["ALT","BILI"])].pivot_table(index=["USUBJID","ACTARM"],columns="PARAMCD",values="XULN",aggfunc="max").reset_index()
pk["Quadrant"]=pk.apply(lambda r:("Potential Hy's Law" if r.BILI>2 else "Temple's corollary (ALT>3xULN)") if r.ALT>3 else ("Hyperbilirubinemia" if r.BILI>2 else "Normal range"),axis=1)
o+=[md(pd.crosstab(pk.Quadrant,pk.ACTARM)),"\n### Subjects outside the normal quadrant\n",md(pk[pk.Quadrant!="Normal range"].set_index("USUBJID").round(2)),
"\n## Exercise 8 – Subject 01-701-1211: liver tests over time (×ULN)\n",
md(lb[(lb.USUBJID=="01-701-1211")&lb.PARAMCD.isin(["ALT","AST","BILI"])].pivot_table(index="AVISIT",columns="PARAMCD",values="XULN").reindex(order))]
open("practice/module2/SOLUTIONS.md","w").write("\n".join(o))
print("ok")
