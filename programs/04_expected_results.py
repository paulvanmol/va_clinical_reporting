pm = pulse.groupby(["AVISITN", "TRTA"]).AVAL.mean().unstack().reindex(columns=ARMS).round(1)
post = pulse[pulse.ADY >= 1]
brady50 = post[post.AVAL < 50].groupby("TRTA").USUBJID.nunique().reindex(ARMS).fillna(0).astype(int)
brady55 = post[post.AVAL < 55].groupby("TRTA").USUBJID.nunique().reindex(ARMS).fillna(0).astype(int)
for a in ARMS:
    add("M2_03_PULSE_LT50_SUBJECTS", a, brady50[a])
    add("M2_04_PULSE_LT55_SUBJECTS", a, brady55[a])
low50 = post[post.AVAL < 50][["USUBJID", "TRTA", "AVISIT", "ADY", "AVAL"]].sort_values(["AVAL", "USUBJID"])

# standing minus lying (orthostatic) at week 24 mean change in pulse
alt = adlbc[(adlbc.PARAMCD == "ALT") & (adlbc.ADY >= 1)]
worst_alt = alt.groupby("USUBJID").agg(ANRIND=("ANRIND", lambda x: "H" if (x == "H").any() else "N"), TRTA=("TRTA", "first")).reset_index()
base_alt = adlbc[(adlbc.PARAMCD == "ALT") & (adlbc.ABLFL == "Y")][["USUBJID", "BNRIND"]].drop_duplicates("USUBJID")
sh = worst_alt.merge(base_alt, on="USUBJID", how="left")
sh["BNRIND"] = sh.BNRIND.fillna("(missing)")
shift = sh.groupby(["TRTA", "BNRIND", "ANRIND"]).size().unstack(fill_value=0).reindex(ARMS, level=0)
n2h = sh[(sh.BNRIND == "N") & (sh.ANRIND == "H")].groupby("TRTA").size().reindex(ARMS).fillna(0).astype(int)
for a in ARMS:
    add("M2_05_ALT_NORMAL_TO_HIGH_SUBJECTS", a, n2h[a])

edc = ed.groupby(["EDISHCAT", "TRT01A"]).USUBJID.nunique().unstack().reindex(columns=ARMS).fillna(0).astype(int)
for cat in ["Normal", "Temple's Corollary", "Hyperbilirubinemia", "Potential Hy's Law"]:
    for a in ARMS:
        add("M2_06_EDISH|" + cat, a, edc.loc[cat, a] if cat in edc.index else 0)
add("M2_06_EDISH_N", "all", len(ed))
