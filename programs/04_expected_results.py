subj_teae = teae.USUBJID.nunique()
add("M1_03_SUBJECTS_WITH_AE", "any AE", subj_any)
add("M1_03_SUBJECTS_WITH_AE", "TEAE", subj_teae)
t_subj = by_arm(teae.groupby("TRTA").USUBJID.nunique())
t_rec = by_arm(teae.groupby("TRTA").size())
for a in ARMS:
    add("M1_04_TEAE_SUBJECTS", a, t_subj[a])
    add("M1_05_TEAE_RECORDS", a, t_rec[a])
sev = teae[teae.AESEV == "SEVERE"]
sev_s = by_arm(sev.groupby("TRTA").USUBJID.nunique())
for a in ARMS:
    add("M1_06_SEVERE_SUBJECTS", a, sev_s[a])
add("M1_06_SEVERE_RECORDS", "all", len(sev))
soc = teae.groupby(["AEBODSYS", "TRTA"]).USUBJID.nunique().unstack().reindex(columns=ARMS).fillna(0).astype(int)
for s_, row in soc.iterrows():
    for a in ARMS:
        add("M1_07_SOC_SUBJECTS|" + s_, a, row[a])
app = teae[teae.AEDECOD.str.contains("APPLICATION SITE")]
app_s = by_arm(app.groupby("TRTA").USUBJID.nunique())
for a in ARMS:
    add("M1_08_APPLICATION_SITE_SUBJECTS", a, app_s[a])
ser = adae[adae.AESER == "Y"]
add("M1_09_SERIOUS_AE_RECORDS", "all", len(ser))

# worst severity per subject
rank = {"MILD": 1, "MODERATE": 2, "SEVERE": 3}
worst = teae.assign(r=teae.AESEV.map(rank)).groupby(["TRTA", "USUBJID"]).r.max().reset_index()
worst_t = worst.groupby(["r", "TRTA"]).size().unstack().reindex(columns=ARMS).fillna(0).astype(int)
worst_t.index = [{1: "MILD", 2: "MODERATE", 3: "SEVERE"}[i] for i in worst_t.index]
worst_t.index.name = "Worst severity"
for s_, row in worst_t.iterrows():
    for a in ARMS:
        add("M1_10_WORST_SEVERITY_SUBJECTS|" + s_, a, row[a])

# AEs by AESEV (subject appears in each severity he/she had)
sev_any = teae.groupby(["AESEV", "TRTA"]).USUBJID.nunique().unstack().reindex(columns=ARMS).fillna(0).astype(int)

# 5-year age groups
bins = list(range(50, 95, 5))
adsl["AGE5"] = pd.cut(adsl.AGE, bins=bins, right=False, labels=[f"{b}-{b+4}" for b in bins[:-1]])
age5 = adsl.groupby("AGE5", observed=False).USUBJID.nunique()

pct = (t_subj / arm_n * 100).round(1)
wrong_den = (t_subj / t_subj * 100).round(1)

demo_sex = adsl.groupby(["TRT01A", "SEX"]).USUBJID.nunique().unstack().reindex(ARMS)
demo_age = adsl.groupby("TRT01A").AGE.agg(["count", "min", "mean", "max"]).reindex(ARMS).round(1)
demo_race = adsl.groupby(["RACE", "TRT01A"]).USUBJID.nunique().unstack().reindex(columns=ARMS).fillna(0).astype(int)


def subj_profile(u):
    r = adae[adae.USUBJID == u][["AEDECOD", "AESEV", "AESER", "AEREL", "ASTDY", "AEOUT"]].sort_values("ASTDY")
    return r


