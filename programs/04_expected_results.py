import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def D(n):
    df = pd.read_csv(os.path.join(ROOT, "data", n + ".csv"), keep_default_na=False, na_values=[""])
    for c in df.columns:
        if df[c].dtype == object or str(df[c].dtype).startswith("str"):
            df[c] = df[c].str.strip()
    return df



adsl, adae, advs, adlbc, hy, ed = (D(n) for n in ["adsl", "adae", "advs", "adlbc", "adlbhy", "adedish"])

ARMS = ["Placebo", "Xanomeline Low Dose", "Xanomeline High Dose"]
checks = []          # (check_id, group, expected)


def add(cid, grp, val):
    checks.append((cid, str(grp), float(val)))


def md(df, index=True):
    df = df.reset_index() if index else df
    cols = [str(c) for c in df.columns]
    rows = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        rows.append("| " + " | ".join(("%g" % v if isinstance(v, float) else str(v)) for v in r) + " |")
    return "\n".join(rows)


def by_arm(series):
    return series.reindex(ARMS).fillna(0).astype(int)


# =============================================================== MODULE 1
teae = adae[(adae.SAFFL == "Y") & (adae.TRTEMFL == "Y")]
arm_n = adsl.groupby("TRT01A").USUBJID.nunique().reindex(ARMS)
for a in ARMS:
    add("M1_01_N_SUBJECTS", a, arm_n[a])
add("M1_02_ROWS", "ADSL", len(adsl))
add("M1_02_ROWS", "ADAE", len(adae))
add("M1_02_ROWS", "ADAE_TEAE", len(teae))
