adex = adsl.copy()
dur = adex.groupby("TRT01A").TRTDUR.agg(["count", "min", "mean", "max"]).reindex(ARMS).round(1)
for a in ARMS:
    add("M2_01_N_EXPOSURE", a, dur.loc[a, "count"])
