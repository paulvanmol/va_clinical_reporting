add("M2_07_ADLBHY_HYLAW_SUBJECTS", "all", hyl.USUBJID.nunique())
cands = ed[ed.EDISHCAT != "Normal"][["USUBJID", "TRT01A", "ALTXULN", "ASTXULN", "BILIXULN", "EDISHCAT"]].round(2)

s1186 = adlbc[(adlbc.USUBJID == "01-705-1186") & adlbc.PARAMCD.isin(["ALT", "AST", "BILI"]) & adlbc.AVISITN.isin([0, 2, 4])]
